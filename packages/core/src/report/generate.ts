import type { Severity } from "../events/types.js";
import type { Cvss, Evidence, Finding } from "../evidence/models.js";

/**
 * Client-ready report. Markdown is canonical; a PDF pass (marked -> HTML ->
 * puppeteer) is layered on in the polish window. The goal: a stranger reads one
 * finding and understands the issue, its proof, and its fix without help.
 */

const SEVERITY_ORDER: Severity[] = ["critical", "high", "medium", "low", "info"];
const SEVERITY_RANK: Record<Severity, number> = {
  critical: 0,
  high: 1,
  medium: 2,
  low: 3,
  info: 4,
};

export interface ReportMeta {
  /** ISO date; defaults to today. Pinned input keeps the report reproducible. */
  generatedOn?: string;
  objective?: string;
}

export function toMarkdown(findings: Finding[], target: string, meta: ReportMeta = {}): string {
  const date = meta.generatedOn ?? new Date().toISOString().slice(0, 10);
  const ordered = [...findings].sort(
    (a, b) => SEVERITY_RANK[a.severity] - SEVERITY_RANK[b.severity],
  );

  const out: string[] = [
    "# Nightfall — Penetration Test Report",
    "",
    `**Target:** ${target}`,
    meta.objective ? `**Objective:** ${meta.objective}` : "",
    `**Generated:** ${date}`,
    "**Scope:** authorized, isolated lab only — see AUTHORIZATION.md",
    "",
    "---",
    "",
    "## Summary",
    "",
    summaryLine(ordered),
    "",
    ...summaryTable(ordered),
    "",
    "---",
    "",
    "## Findings",
    "",
  ];

  if (ordered.length === 0) {
    out.push("No vulnerabilities were confirmed within scope during this run.", "");
  }

  ordered.forEach((f, i) => {
    out.push(...renderFinding(f, i + 1));
  });

  out.push(
    "---",
    "",
    "_Generated by Nightfall. All testing was performed against an authorized,",
    "isolated target as defined in the scope file. Every request shown passed the",
    "deny-by-default scope gate._",
    "",
  );

  return out.filter((l) => l !== null).join("\n");
}

function summaryLine(findings: Finding[]): string {
  if (findings.length === 0) return "**0 findings.**";
  const counts = SEVERITY_ORDER.map((s) => ({
    s,
    n: findings.filter((f) => f.severity === s).length,
  })).filter((c) => c.n > 0);
  const parts = counts.map((c) => `${c.n} ${c.s}`);
  const total = findings.length;
  return `**${total} finding${total === 1 ? "" : "s"}:** ${parts.join(", ")}.`;
}

function summaryTable(findings: Finding[]): string[] {
  if (findings.length === 0) return [];
  const rows = findings.map((f, i) => {
    const anchor = `#${i + 1}-${slug(f.title)}`;
    return `| ${i + 1} | [${escapeCell(f.title)}](${anchor}) | ${badge(f.severity)} | ${cvssCell(f.cvss)} |`;
  });
  return ["| # | Finding | Severity | CVSS |", "| --- | --- | --- | --- |", ...rows];
}

function renderFinding(f: Finding, n: number): string[] {
  const lines: string[] = [`### ${n}. ${f.title} ${badge(f.severity)}`, ""];

  if (f.cvss) {
    const vector = f.cvss.vector ? ` \`${f.cvss.vector}\`` : "";
    lines.push(`**CVSS:** ${f.cvss.score.toFixed(1)} (${cvssBand(f.cvss.score)})${vector}`, "");
  }

  if (f.description) lines.push(f.description, "");

  if (f.evidence.length > 0) {
    lines.push("**Evidence**", "");
    f.evidence.forEach((e, i) => {
      lines.push(...renderEvidence(e, i + 1, f.evidence.length));
    });
  }

  lines.push("**Remediation**", "", f.remediation || "_No remediation provided._", "", "---", "");
  return lines;
}

function renderEvidence(e: Evidence, i: number, total: number): string[] {
  const lines: string[] = [];
  if (total > 1) lines.push(`_Evidence ${i} of ${total}_`, "");
  if (e.note) lines.push(e.note, "");
  lines.push("Request:", "", fence("http", e.request), "");
  lines.push("Response:", "", fence("http", e.response), "");
  if (e.screenshot) lines.push(`![Execution proof](${e.screenshot})`, "");
  return lines;
}

function badge(s: Severity): string {
  return `\`${s.toUpperCase()}\``;
}

function cvssCell(cvss?: Cvss): string {
  return cvss ? `${cvss.score.toFixed(1)} (${cvssBand(cvss.score)})` : "—";
}

/** CVSS v3.1 qualitative bands. */
function cvssBand(score: number): string {
  if (score === 0) return "None";
  if (score < 4) return "Low";
  if (score < 7) return "Medium";
  if (score < 9) return "High";
  return "Critical";
}

/** Fence that can't be broken by backticks inside the body. */
function fence(lang: string, body: string): string {
  let ticks = 3;
  for (const run of body.match(/`+/g) ?? []) ticks = Math.max(ticks, run.length + 1);
  const bar = "`".repeat(ticks);
  return `${bar}${lang}\n${body}\n${bar}`;
}

function slug(title: string): string {
  return title
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function escapeCell(text: string): string {
  return text.replace(/\|/g, "\\|");
}
